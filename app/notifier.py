"""Notifications: PDF claim voucher + HTML email via Gmail SMTP.

Email failures never block the workflow: they are retried (3 attempts with backoff),
logged and recorded in the audit trail, and the claim decision stays saved.
"""
import json
import smtplib
import time
from email.message import EmailMessage
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Image, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
from tenacity import retry, stop_after_attempt, wait_exponential

from app import config, db
from app.config import load_policy
from app.logger import get_logger

STATUS_COLORS = {
    "AUTO_APPROVED": "#15803d", "APPROVED": "#15803d",
    "REJECTED": "#b91c1c", "AUTO_REJECTED": "#b91c1c", "DUPLICATE": "#b91c1c",
}


def _money(claim: dict) -> str:
    if claim.get("total_amount") is None:
        return "-"
    return f"{claim.get('currency') or 'INR'} {claim['total_amount']:,.2f}"


def _pdf(text) -> str:
    """Built-in PDF fonts lack the rupee sign and arrows."""
    return str(text).replace("₹", "Rs.").replace("→", "->")


def build_voucher(claim: dict) -> Path:
    """Generates a PDF voucher with claim details, decision, policy flags and the audit trail."""
    path = config.VOUCHERS_DIR / f"{claim['id']}.pdf"
    styles = getSampleStyleSheet()
    color = STATUS_COLORS.get(claim["status"], "#a16207")
    story = [
        Paragraph(f"<b>{load_policy()['company']}</b>", styles["Title"]),
        Paragraph("Expense Claim Voucher &mdash; generated by ClaimFlow AI", styles["Normal"]),
        Spacer(1, 6 * mm),
        Paragraph(f"<font color='{color}'><b>{claim['status'].replace('_', ' ')}</b></font>"
                  f" &nbsp; | &nbsp; Claim ID: <b>{claim['id']}</b>", styles["Heading2"]),
    ]
    rows = [
        ["Employee", claim.get("employee_name") or "-"], ["Purpose", claim.get("purpose") or "-"],
        ["Vendor", claim.get("vendor") or "-"], ["Receipt date", claim.get("receipt_date") or "-"],
        ["Invoice no.", claim.get("invoice_number") or "-"], ["Category", claim.get("category") or "-"],
        ["Amount", _money(claim)], ["AI confidence", f"{(claim.get('confidence') or 0):.0%}"],
        ["Risk score", f"{claim.get('risk_score') or 0} / 100"], ["Decided by", claim.get("decided_by") or "-"],
        ["Reason", Paragraph(_pdf(claim.get("reason") or "-"), styles["Normal"])],
        ["Submitted", claim["created_at"]], ["Last updated", claim["updated_at"]],
    ]
    t = Table(rows, colWidths=[40 * mm, 125 * mm])
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
                           ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f1f5f9")),
                           ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story += [t, Spacer(1, 5 * mm)]

    flags = json.loads(claim.get("flags_json") or "[]")
    if flags:
        story.append(Paragraph("Policy & risk checks", styles["Heading3"]))
        ft = Table([["Rule", "Severity", "Detail", "Pts"]] +
                   [[f["code"], f["severity"], Paragraph(_pdf(f["message"]), styles["Normal"]), f["points"]] for f in flags],
                   colWidths=[50 * mm, 17 * mm, 88 * mm, 10 * mm])
        ft.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
                                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e2e8f0"))]))
        story += [ft, Spacer(1, 5 * mm)]

    trail = db.audit_trail(claim["id"])
    if trail:
        story.append(Paragraph("Audit trail", styles["Heading3"]))
        at = Table([["Time", "Actor", "Action", "Status"]] +
                   [[a["ts"].replace("T", " "), a["actor"], a["action"],
                     f"{a['from_status'] or ''} -> {a['to_status'] or ''}"] for a in trail],
                   colWidths=[35 * mm, 30 * mm, 50 * mm, 50 * mm])
        at.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, colors.grey), ("FONTSIZE", (0, 0), (-1, -1), 7),
                                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e2e8f0"))]))
        story += [at, Spacer(1, 5 * mm)]

    img = claim.get("image_path")
    if img and Path(img).exists():
        story += [Paragraph("Attached receipt", styles["Heading3"]),
                  Image(img, width=60 * mm, height=80 * mm, kind="proportional")]
    SimpleDocTemplate(str(path), pagesize=A4, topMargin=15 * mm, bottomMargin=15 * mm).build(story)
    return path


@retry(stop=stop_after_attempt(3), wait=wait_exponential(multiplier=2, min=2, max=8), reraise=True)
def _send(msg: EmailMessage) -> None:
    with smtplib.SMTP_SSL("smtp.gmail.com", 465, timeout=20) as s:
        s.login(config.GMAIL_ADDRESS, config.GMAIL_APP_PASSWORD)
        s.send_message(msg)


def send_decision_email(claim_id: str) -> bool:
    """Builds the voucher and emails it. Returns True on success, False on (logged) failure."""
    log = get_logger(claim_id, "notify")
    claim = db.get_claim(claim_id)
    try:
        pdf = build_voucher(claim)
        log.info(f"PDF voucher generated: {pdf.name}")
    except Exception as e:
        log.error(f"Voucher generation failed: {e}")
        pdf = None

    if not (config.EMAIL_ENABLED and config.GMAIL_ADDRESS and config.GMAIL_APP_PASSWORD):
        log.warning("Email disabled or not configured - skipping")
        return False

    status = claim["status"].replace("_", " ").title()
    color = STATUS_COLORS.get(claim["status"], "#a16207")
    msg = EmailMessage()
    msg["Subject"] = f"[ClaimFlow AI] {claim['id']} {status} - {_money(claim)}"
    msg["From"] = f"ClaimFlow AI <{config.GMAIL_ADDRESS}>"
    # Employee's registered email (optional, set in the bot); otherwise the finance mailbox.
    employee = (db.get_user(claim["chat_id"]) or {}).get("email") if claim.get("chat_id") else None
    to = employee or config.NOTIFY_EMAIL
    msg["To"] = to
    if employee and config.NOTIFY_EMAIL and config.NOTIFY_EMAIL.lower() != employee.lower():
        msg["Cc"] = config.NOTIFY_EMAIL  # finance copy
    msg.set_content(f"Claim {claim['id']} is {status}. Reason: {claim.get('reason')}")
    msg.add_alternative(f"""
    <div style="font-family:Segoe UI,Arial,sans-serif;max-width:560px">
      <h2 style="margin-bottom:4px">ClaimFlow AI</h2>
      <p style="color:#64748b;margin-top:0">Automated expense claim notification</p>
      <div style="border-left:6px solid {color};padding:10px 14px;background:#f8fafc">
        <div style="font-size:20px;color:{color};font-weight:700">{status}</div>
        <div>Claim <b>{claim['id']}</b> &middot; {_money(claim)}</div>
      </div>
      <table style="margin-top:12px;border-collapse:collapse">
        <tr><td style="padding:4px 12px 4px 0;color:#64748b">Vendor</td><td>{claim.get('vendor') or '-'}</td></tr>
        <tr><td style="padding:4px 12px 4px 0;color:#64748b">Date</td><td>{claim.get('receipt_date') or '-'}</td></tr>
        <tr><td style="padding:4px 12px 4px 0;color:#64748b">Category</td><td>{claim.get('category') or '-'}</td></tr>
        <tr><td style="padding:4px 12px 4px 0;color:#64748b">Purpose</td><td>{claim.get('purpose') or '-'}</td></tr>
        <tr><td style="padding:4px 12px 4px 0;color:#64748b">Risk score</td><td>{claim.get('risk_score') or 0}/100</td></tr>
        <tr><td style="padding:4px 12px 4px 0;color:#64748b">Decided by</td><td>{claim.get('decided_by') or '-'}</td></tr>
        <tr><td style="padding:4px 12px 4px 0;color:#64748b">Reason</td><td>{claim.get('reason') or '-'}</td></tr>
      </table>
      <p style="color:#64748b;font-size:12px">The PDF voucher with the full audit trail is attached.</p>
    </div>""", subtype="html")
    if pdf:
        msg.add_attachment(pdf.read_bytes(), maintype="application", subtype="pdf", filename=pdf.name)

    t0 = time.perf_counter()
    try:
        _send(msg)
        db.record_metric("gmail", True, int((time.perf_counter() - t0) * 1000))
        db.audit(claim_id, "system", "EMAIL_SENT", details={"to": to, "cc": msg["Cc"]})
        log.success(f"Decision email sent to {to}" + (f" (cc {msg['Cc']})" if msg["Cc"] else ""))
        return True
    except Exception as e:
        db.record_metric("gmail", False, int((time.perf_counter() - t0) * 1000), str(e)[:300])
        db.audit(claim_id, "system", "EMAIL_FAILED", details={"error": str(e)[:300]})
        log.error(f"Email failed after 3 attempts: {e} (claim decision is saved; notification can be resent)")
        return False
